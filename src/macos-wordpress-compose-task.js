import { buildWordpressComposeTask } from './wordpress-compose-task.js'

const IMAGES = [
  'wordpress:7.0.2-php8.3-fpm',
  'wordpress:cli-2.12.0-php8.3',
  'nginx:1.30.4-alpine',
  'mariadb:11.8.8'
]

export function buildMacosWordpressComposeTask (taskId, execution = {}, docker = {}) {
  if (execution.platform !== 'macos') throw new Error('macOS WordPress requires signed macOS execution inventory')
  if (!/^[a-z_][a-z0-9_-]{0,31}$/u.test(execution.runtimeUser ?? '') || !/^\/Users\/[a-z_][a-z0-9_-]{0,31}$/u.test(execution.runtimeHome ?? '')) throw new Error('macOS WordPress requires a reviewed non-root Homebrew owner')
  if (docker.ready !== true) throw new Error('macOS WordPress requires the reviewed Colima prerequisite')
  const home = execution.runtimeHome
  const serviceRoot = `${home}/.webminai/services/wordpress`
  const credentials = `${home}/.webminai/credentials/wordpress`
  const state = `/var/db/webminai/task-state/${taskId}-wordpress-compose`
  const built = buildWordpressComposeTask(taskId, {
    identity: { id: 'ubuntu', versionId: '24.04' },
    applications: { wordpress: { primaryAddressCommand: "ifconfig | awk '/^[a-z0-9]+:/{iface=$1; sub(/:$/,\"\",iface)} /inet / && $2 != \"127.0.0.1\" {print $2; exit}'" } }
  }, { preferred: true, ready: true, installMethod: 'homebrew-colima' })

  for (const item of [...built.plan.commands, ...built.plan.revertCommands]) {
    item.command = adaptCommand(item.command, taskId, home)
  }
  replaceCommand(built.plan.commands, 'capture-baseline', baselineCommand({ state, serviceRoot, credentials, home }))
  replaceCommand(built.plan.commands, 'prepare-docker', dockerReadyCommand(state, home))
  const credentialCommand = built.plan.commands.find(item => item.id === 'generate-credentials')
  if (!credentialCommand) throw new Error('WordPress Compose plan is missing generate-credentials')
  credentialCommand.command += `; chown ${quote(execution.runtimeUser)}:staff ${quote(`${home}/.webminai`)}; chmod 0700 ${quote(`${home}/.webminai`)}; install -d -o ${quote(execution.runtimeUser)} -g staff -m 0700 ${quote(`${home}/.webminai/credentials`)}; chown -R ${quote(execution.runtimeUser)}:staff ${quote(credentials)}; chmod 0700 ${quote(credentials)}; chmod 0600 ${quote(`${credentials}/db_password`)} ${quote(`${credentials}/db_root_password`)} ${quote(`${credentials}/admin_password`)}`
  replaceCommand(built.plan.revertCommands, 'restore-docker', `set -eu; rm -rf -- ${quote(state)}; printf '%s\n' colima-preserved`)
  for (const item of [...built.plan.commands, ...built.plan.revertCommands]) {
    if (['pull-images', 'start-compose', 'initialize-wordpress', 'verify-compose', 'remove-compose-project', 'remove-compose-images'].includes(item.id)) {
      item.executionMode = 'job'
      item.timeoutMs = 30 * 60 * 1000
    }
  }
  built.plan.summary = 'Deploy a learned reversible macOS WordPress Compose site'
  built.plan.changeOverview = 'Reuse the promoted ismet WordPress image matrix through the reviewed Colima socket, with macOS-home bind paths and host-generated credentials.'
  built.plan.modifiedFiles = [state, serviceRoot, credentials]
  built.plan.assumptions = [
    'Signed macOS inventory reports the reviewed Colima Docker and Compose substrate ready.',
    'The shared Colima VM is a prerequisite and is preserved by application rollback.',
    `Credential files are generated by Stage 2, then restricted to the Colima owner ${execution.runtimeUser} so virtiofs can mount them without exposing their values.`,
    'The stable Compose project, macOS service paths, credentials, and port 18101 are unused before execution.'
  ]
  built.verifyApplied = adaptCommand(built.verifyApplied, taskId, home)
  built.verifyReverted = adaptCommand(built.verifyReverted, taskId, home)
  built.stateProbe = adaptCommand(built.stateProbe, taskId, home)
  return built
}

function baselineCommand ({ state, serviceRoot, credentials, home }) {
  const captureImages = IMAGES.map((image, index) => `if docker image inspect ${quote(image)} >/dev/null 2>&1; then : > ${quote(`${state}/image-${index}.existed`)}; fi`)
  return withDocker([
    'set -eu',
    `if [ ! -e ${quote(`${state}/baseline.ready`)} ]; then test ! -e ${quote(serviceRoot)}; test ! -e ${quote(credentials)}; install -d -o root -g wheel -m 0700 ${quote(state)}; ${captureImages.join('; ')}; : > ${quote(`${state}/baseline.ready`)}; fi`,
    "printf '%s\n' baseline-ready"
  ].join('; '), home)
}

function dockerReadyCommand (state, home) {
  return withDocker(`set -eu; docker info >/dev/null; docker compose version >/dev/null; : > ${quote(`${state}/docker-ready.before`)}; printf '%s\n' docker-ready`, home)
}

function adaptCommand (command, taskId, home) {
  const adapted = String(command)
    .replaceAll(`/var/lib/webminai/task-state/${taskId}-wordpress-compose`, `/var/db/webminai/task-state/${taskId}-wordpress-compose`)
    .replaceAll('/opt/webminai/services/wordpress', `${home}/.webminai/services/wordpress`)
    .replaceAll('/root/wordpress_credentials', `${home}/.webminai/credentials/wordpress`)
    .replaceAll('-g root', '-g wheel')
    .replaceAll('$(seq 1 ', '$(jot ')
  return withDocker(adapted, home)
}

function withDocker (command, home) {
  const prefix = `export HOME=${quote(home)} PATH='/usr/local/bin:/usr/local/sbin:/usr/bin:/bin:/usr/sbin:/sbin' DOCKER_HOST=${quote(`unix://${home}/.colima/default/docker.sock`)}`
  return command.startsWith(`${prefix}; `) ? command : `${prefix}; ${command}`
}

function replaceCommand (items, id, command) {
  const item = items.find(item => item.id === id)
  if (!item) throw new Error(`WordPress Compose plan is missing ${id}`)
  item.command = command
}

function quote (value) {
  return `'${String(value).replaceAll("'", "'\\''")}'`
}
